package Strings;

public class CompareTo {
    static void main() {
        String a = "ragahav";
        String b = "preet"; //p+2=r {p,q,r} (r-p print)
        System.out.println(a.compareTo(b));
        String x = "harmeet";
        String y = "harsh"; //m+6 =s {m,n,o,p,q,r,s}
        System.out.println(x.compareTo(y));
    }
}
